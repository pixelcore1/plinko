#!/usr/bin/env python3
"""Build design-system/css/tokens.css and design-system/css/type.css from the Figma export.

Input (made by scripts/export-css.figma.js, run read-only in Figma through the Figma connector):
  scripts/figma-export/variables-primitives.txt
  scripts/figma-export/variables-rest.txt
  scripts/figma-export/styles.txt

Rules
- Every CSS name comes from the Figma code syntax (WEB). Figma and code use the same names.
- Aliases stay aliases: var(--target). The chain Components -> Semantic -> Primitives survives in code.
- Alpha primitives (White Alpha, Black Alpha, Magenta Alpha, Gold Alpha) are color-mix() of their base colour,
  so changing the base colour changes the alpha ramp, as in Figma.
- Modes: Tokens/Desktop -> @media (min-width: 1024px). Motion/Reduced -> @media (prefers-reduced-motion: reduce).
  Bin heat modes -> [data-heat="cold"] ... [data-heat="mega"].
- Selectors are ":root, :host" so the tokens also work inside a Shadow DOM root.
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'scripts' / 'figma-export'
OUT = ROOT / 'design-system' / 'css'

ALPHA_BASE = {'white-alpha': 'neutral-50', 'black-alpha': 'neutral-950',
              'magenta-alpha': 'magenta-500', 'gold-alpha': 'gold-300'}


def parse(text):
    """Return {block_name: [(css_name, value, figma_name)]} in source order."""
    blocks, cur = {}, None
    for line in text.splitlines():
        m = re.match(r'/\* (.+?) \*/$', line.strip())
        if m:
            cur = m.group(1); blocks[cur] = []; continue
        m = re.match(r'(--[\w-]+): (.*?);(?: /\*(.*)\*/)?$', line.strip())
        if m and cur:
            blocks[cur].append((m.group(1), m.group(2), m.group(3) or ''))
    return blocks


def fix(name, value, figma):
    a = re.match(r'--(white|black|magenta|gold)-alpha-(\d+)$', name)
    if a:
        base = ALPHA_BASE[a.group(1) + '-alpha']
        return f'color-mix(in srgb, var(--{base}) {a.group(2)}%, transparent)'
    n = re.match(r'N:([\d.]+):', value)
    if n:
        v = float(n.group(1))
        key = (figma or name).lower()
        if 'duration' in key:
            return f'{round(v * 1000)}ms'
        if 'weight' in key:
            return str(round(v))
        return f'{v:g}px'
    return value


def block(selector, rows, indent='  '):
    body = '\n'.join(f'{indent}{n}: {v};' for n, v in rows)
    return f'{selector} {{\n{body}\n}}\n'


def main():
    prim = parse((SRC / 'variables-primitives.txt').read_text())
    rest = parse((SRC / 'variables-rest.txt').read_text())
    allb = {**prim, **rest}
    rows = lambda key: [(n, fix(n, v, f)) for n, v, f in allb[key]]

    css = ['/* Plinko design tokens. Generated by scripts/build-tokens.py from the Figma variables.\n'
           '   Do not edit by hand: change the variable in Figma, export, build.\n'
           '   File: https://www.figma.com/design/EXcHZLG3O0BS12H0wqYm7i */\n']
    for key, title in [('Primitives / Mode 1', 'Primitives'), ('Typography / Mode 1', 'Typography'),
                       ('Tokens / Mobile', 'Tokens (Mobile, default)'), ('Semantic / Dark', 'Semantic'),
                       ('Components / Dark', 'Components'), ('Motion / Default', 'Motion (Default)')]:
        css.append(f'\n/* {title} */\n' + block(':root, :host', rows(key)))
    css.append('\n/* Tokens (Desktop): starts at --utilities-breakpoint-desktop (1024px) */\n'
               '@media (min-width: 1024px) {\n' + block('  :root, :host', rows('Tokens / Desktop'), '    ') + '}\n')
    css.append('\n/* Tokens (Mobile) on demand: the game popup is a mobile layout at every width, so it pins this mode */\n' + block('[data-token-mode="mobile"]', [r for r in rows('Tokens / Mobile') if r[0] in dict(rows('Tokens / Desktop'))]))
    css.append('\n/* Motion (Reduced): short fades, loops off */\n'
               '@media (prefers-reduced-motion: reduce) {\n' + block('  :root, :host', rows('Motion / Reduced'), '    ') + '}\n')
    css.append('\n/* Manual override for docs and tests: <html data-motion="reduced"> */\n'
               + block('[data-motion="reduced"]', rows('Motion / Reduced')))
    # Bin heat: default mode is Cold; each heat gets the full set (default + its overrides)
    base = dict((n, v) for n, v in rows('Bin heat / Cold'))
    css.append('\n/* Bin heat: set data-heat on a bin (or a chip), its colours follow */\n')
    css.append(block(':root, :host', list(base.items())))
    for heat in ['Cold', 'Cool', 'Mild', 'Warm', 'Hot', 'Mega']:
        d = dict(base); d.update(dict(rows(f'Bin heat / {heat}')))
        css.append(block(f'[data-heat="{heat.lower()}"]', list(d.items())))

    # Styles: gradients, effects
    styles = (SRC / 'styles.txt').read_text().splitlines()
    grad, fx, typ = [], [], []
    slug = lambda s: re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')
    for line in styles:
        kind, name, spec = line.split('|', 2)
        if kind == 'P':
            layers = []
            for p in spec.split(' || '):
                if p.startswith('solid '):
                    c = p[6:]; layers.append(f'linear-gradient({c}, {c})')
                elif p.startswith('GRADIENT_LINEAR'):
                    stops = re.sub(r'^GRADIENT_LINEAR T\[[^\]]*\] ', '', p)
                    layers.append(f'linear-gradient(180deg, {stops})')
                elif p.startswith('GRADIENT_RADIAL'):
                    stops = re.sub(r'^GRADIENT_RADIAL T\[[^\]]*\] ', '', p)
                    layers.append(f'radial-gradient(circle at 50% 50%, {stops})')
            if layers:
                grad.append((f'--gradient-{slug(name)}', ', '.join(reversed(layers))))
        elif kind == 'E':
            parts = spec.split(' || ')
            if parts[0].startswith('BACKGROUND_BLUR'):
                continue  # blur uses --blur-* tokens directly
            sh = []
            for p in parts:
                m = re.match(r'DROP_SHADOW x([-\d.]+) y([-\d.]+) b([-\d.]+) s([-\d.]+) (.+)$', p)
                if m:
                    x, y, b, s, c = m.groups()
                    sh.append(f'{x}px {y}px {b}px {s}px {c}')
            fx.append((f'--{slug(name).replace("glow-", "glow-").replace("shadow-", "shadow-")}', ', '.join(sh)))
        elif kind == 'T':
            typ.append((name, spec))
    css.append('\n/* Paint styles (gradients). Layer order: top layer first, as CSS expects */\n' + block(':root, :host', grad))
    css.append('\n/* Effect styles (glows and shadows) */\n' + block(':root, :host', fx))
    (OUT / 'tokens.css').write_text(''.join(css))

    # Text styles -> classes
    out = ['/* Text styles from Figma. Generated by scripts/build-tokens.py. Class = Figma style name. */\n']
    for name, spec in typ:
        f = dict(x.split(' ', 1) for x in spec.split('|')[1:])
        m = re.match(r'(Headline|Body|Title|Label|Number|Components/Button)/(\S+)', name)
        group, size = m.group(1), m.group(2)
        weight = 'bold' if 'bold' in name else 'medium' if 'medium' in name else ''
        cls = {'Components/Button': 'text-button'}.get(group, 'text-' + group.lower())
        cls += '-' + size.lower() + ('-' + weight if group in ('Headline', 'Body') else '')
        lh = f['lh'].replace('PERCENT', '')
        ls = f['ls'].replace('PERCENT', '')
        decl = [f"font-family: {f['fam']}, system-ui, sans-serif", f"font-size: {f['size']}",
                f"font-weight: {f['w']}", f'line-height: {float(lh) / 100:g}']
        if float(ls):
            decl.append(f'letter-spacing: {float(ls) / 100:g}em')
        if f['case'] == 'UPPER':
            decl.append('text-transform: uppercase')
        out.append(f'.{cls} {{ ' + '; '.join(decl) + '; } /* ' + name + ' */\n')
    (OUT / 'type.css').write_text(''.join(out))
    print('tokens.css', len(''.join(css)), 'type.css', len(''.join(out)))


if __name__ == '__main__':
    main()

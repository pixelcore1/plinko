#!/usr/bin/env bash
# Build everything that is generated. Run from the repo root. Needs Python 3 and Node (npx esbuild).
set -e
python3 scripts/build-tokens.py                          # Figma export -> design-system/css/tokens.css, type.css
python3 - <<'PY'                                          # sounds as data: URLs for file:// use
import base64, os, json
d = 'design-system/assets/sfx'
m = {f: 'data:audio/mpeg;base64,' + base64.b64encode(open(os.path.join(d, f), 'rb').read()).decode() for f in sorted(os.listdir(d)) if f.endswith('.mp3')}
open('design-system/js/sfx-data.js', 'w').write('/* Sound files as data: URLs, generated by scripts/build.sh. Loaded only when the page is opened from a file (file://), where fetch is blocked. */\nwindow.PLINKO_SFX = ' + json.dumps(m) + ';\n')
PY
python3 - <<'PY'                                          # fonts as data: URLs for file:// use
import base64
css = '/* Ubuntu as data: URLs, generated by scripts/build.sh. Loaded only from file://, where the browser blocks font files. */\n'
for w, n in [(300, 'light'), (400, 'regular'), (500, 'medium'), (700, 'bold')]:
    b = base64.b64encode(open(f'design-system/assets/fonts/ubuntu-{n}.woff2', 'rb').read()).decode()
    css += f'@font-face {{ font-family: "Ubuntu"; src: url(data:font/woff2;base64,{b}) format("woff2"); font-weight: {w}; font-display: swap; }}\n'
open('design-system/css/fonts-inline.css', 'w').write(css)
PY
# ES modules don't run from file://, so each page also gets one classic bundle. The modules stay the source.
npx esbuild prototype/js/main.js --bundle --format=iife --target=es2020 --outfile=prototype/js/plinko.js --log-level=warning
npx esbuild design-system/docs/docs.js --bundle --format=iife --target=es2020 --loader:.css=text --outfile=design-system/docs/docs.bundle.js --log-level=warning
echo "build done"
